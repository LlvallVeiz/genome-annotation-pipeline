"""The standard genetic code and basic sequence operations.

The codon table is *built*, not typed: NCBI publishes every genetic code
in a compact form — one amino-acid string plus three base strings
(``Base1``, ``Base2``, ``Base3``) whose columns jointly enumerate the 64
codons. Rebuilding the table from those strings, exactly as printed for
transl_table=1 on NCBI's Genetic Codes page, removes the 64 hand-typed
dictionary entries that would otherwise be a transcription risk. The
tests pin well-known codons (ATG -> M, TGG -> W, the three stop codons)
so a wiring mistake in the construction cannot slip through.
"""

from __future__ import annotations

#: Amino acids of the standard code (NCBI transl_table=1), in the codon
#: order generated by the Base1/Base2/Base3 strings below. ``*`` = stop.
_AMINO_ACIDS = "FFLLSSSSYY**CC*WLLLLPPPPHHQQRRRRIIIMTTTTNNKKSSRRVVVVAAAADDEEGGGG"

#: Base order of NCBI's compact representation: at every codon position
#: the bases cycle through T, C, A, G.
_BASE_ORDER = "TCAG"

#: First base of the 64 codons: 16 x T, then 16 x C, 16 x A, 16 x G.
_BASE1 = "".join(base * 16 for base in _BASE_ORDER)

#: Second base of the 64 codons: TTTTCCCCAAAAGGGG, repeated four times.
_BASE2 = "".join(base * 4 for base in _BASE_ORDER) * 4

#: Third base of the 64 codons: TCAG, repeated sixteen times.
_BASE3 = _BASE_ORDER * 16


def _build_codon_table() -> dict[str, str]:
    """Zip NCBI's four parallel strings into a codon -> amino-acid dict."""
    table: dict[str, str] = {}
    columns = zip(_BASE1, _BASE2, _BASE3, _AMINO_ACIDS)
    for base1, base2, base3, amino_acid in columns:
        table[base1 + base2 + base3] = amino_acid
    return table


#: The standard genetic code: all 64 codons mapped to one-letter amino
#: acids, with the stop codons mapped to ``*``.
CODON_TABLE = _build_codon_table()

#: The stop (termination) codons of the standard code: TAA, TAG, TGA.
STOP_CODONS = frozenset(
    codon for codon, amino_acid in CODON_TABLE.items() if amino_acid == "*"
)

#: The start codon searched for by the ORF finder. ATG is the standard
#: code's initiation codon; alternative initiation codons (GTG, TTG)
#: are deliberately out of scope for this stage.
START_CODON = "ATG"

#: Residue reported for a codon that cannot be resolved to one amino
#: acid — any codon containing an IUPAC ambiguity symbol.
UNKNOWN_AMINO_ACID = "X"

#: IUPAC complement pairs (Cornish-Bowden, 1985): R<->Y, K<->M, B<->V,
#: D<->H, while S, W and N complement to themselves.
_COMPLEMENT_PAIRS = (
    ("A", "T"),
    ("C", "G"),
    ("R", "Y"),
    ("S", "S"),
    ("W", "W"),
    ("K", "M"),
    ("B", "V"),
    ("D", "H"),
    ("N", "N"),
)

_COMPLEMENT: dict[str, str] = {}
for _base, _partner in _COMPLEMENT_PAIRS:
    _COMPLEMENT[_base] = _partner
    _COMPLEMENT[_partner] = _base

_COMPLEMENT_TABLE = str.maketrans(_COMPLEMENT)


def reverse_complement(sequence: str) -> str:
    """Return the reverse complement of a normalised DNA sequence.

    The input is expected to be normalised — upper case, with ``U``
    already converted to ``T`` — as produced by the FASTA parser.
    Ambiguity symbols complement to the symbol for the complementary
    base set, so reverse-complementing loses no information.
    """
    return sequence.translate(_COMPLEMENT_TABLE)[::-1]


def translate(sequence: str) -> str:
    """Translate a DNA sequence in frame +1 with the standard code.

    Args:
        sequence: Normalised DNA sequence (upper case, ``U`` already
            converted to ``T``), as produced by the FASTA parser.

    Returns:
        The one-letter amino-acid sequence. Stop codons translate to
        ``*`` and are included in the result, so a caller can see
        exactly where translation would terminate.

    Edge cases (explicit, by design):

    - If the length is not a multiple of three, the trailing one or two
      bases that cannot form a codon are ignored.
    - A codon containing an IUPAC ambiguity symbol (e.g. ``NNN`` or
      ``ATH``) cannot be resolved to a single amino acid and is
      translated as ``X``, the standard unknown-residue symbol.
    """
    amino_acids = []
    for offset in range(0, len(sequence) - 2, 3):
        codon = sequence[offset : offset + 3]
        amino_acids.append(CODON_TABLE.get(codon, UNKNOWN_AMINO_ACID))
    return "".join(amino_acids)
